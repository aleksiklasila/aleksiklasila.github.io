// Explicit straight-line disk rows. No runtime footprint loops/table lookups
// for radii 1..10. Run after changing the raster definition.
'use strict';
const fs=require('node:fs'),path=require('node:path');
let out='// GENERATED by wasm/generate-occ-shapes.cjs. Raster: dx² + dy² < r².\n';
for(let r=1;r<=10;r++){
 const rows=[];
 for(let y=1-r;y<r;y++){let half=0;for(let x=0;x<r;x++)if(x*x+y*y<r*r)half=x;rows.push([y,half]);}
 const widths=rows.map(([,h])=>2*h+1);
 out+=`\n#[inline(always)]\nunsafe fn mark_r${r}<const MARK: bool>(g:&Grid,cx:i32,cy:i32,layer:i32) {\n    let base=g.bits.add((layer*g.plane+cy*g.stride) as usize);\n`;
 for(const [y,h]of rows)out+=`    row_mark::<MARK>(base.offset((${y}*g.stride) as isize),cx-${h},${2*h+1});\n`;
 out+='}\n';
 out+=`#[inline(always)]\nunsafe fn free_r${r}(g:&Grid,cx:i32,cy:i32,layer:i32,ocx:i32,ocy:i32,own:u64)->bool {\n    let base=g.bits.add((layer*g.plane+cy*g.stride) as usize);\n    let own=own & 0u64.wrapping_sub(((cx-ocx).abs()<${2*r}) as u64) & 0u64.wrapping_sub(((cy-ocy).abs()<${2*r}) as u64);\n`;
 if(r<=3){
  out+=`    let old_left=ocx-${r-1};\n`;
  for(const[y,h]of rows){
   out+=`    let hit${y+r}=row_hit(base.offset((${y}*g.stride) as isize),cx-${h},${2*h+1},old_left,${2*r-1},own & (0u64.wrapping_sub(((cy+${y}-ocy).abs()<${r}) as u64)));\n`;
  }
 }else{
  const lo=widths.slice(0,16),hi=widths.slice(16);while(lo.length<16)lo.push(0);while(hi.length<16)hi.push(0);
  out+=`    let widths0=u8x16(${lo.join(',')});\n    let widths1=u8x16(${hi.join(',')});\n`;
  for(const[y,h]of rows){
   out+=`    let width${y+r}=old_width(widths0,widths1,cy+${y}-ocy+${r-1});\n    let hit${y+r}=row_hit(base.offset((${y}*g.stride) as isize),cx-${h},${2*h+1},ocx-(width${y+r}>>1),width${y+r},own);\n`;
  }
 }
 const hits=rows.map(([y])=>`hit${y+r}`);
 out+=`    finish_hits!(${hits.join(',')})\n}\n`;
}
out+='\n#[inline(always)]\nunsafe fn mark_special<const MARK:bool>(g:&Grid,cx:i32,cy:i32,r:i32,layer:i32) {\n    match r {\n';
for(let r=1;r<=10;r++)out+=`        ${r}=>mark_r${r}::<MARK>(g,cx,cy,layer),\n`;
out+='        _=>unreachable(),\n    }\n}\n';
out+='#[inline(always)]\nunsafe fn free_special(g:&Grid,cx:i32,cy:i32,r:i32,layer:i32,ocx:i32,ocy:i32,own:u64)->bool {\n    match r {\n';
for(let r=1;r<=10;r++)out+=`        ${r}=>free_r${r}(g,cx,cy,layer,ocx,ocy,own),\n`;
out+='        _=>false,\n    }\n}\n';
// Keep shape bodies shared across movement paths. Each body itself is
// straight-line, but inlining all ten shapes at every move bloats the code.
out=out.replaceAll('#[inline(always)]','#[inline(never)]');
fs.writeFileSync(path.join(__dirname,'src/occ_shapes.rs'),out);
console.log('Generated occupancy disk specializations for radii 1..10.');
