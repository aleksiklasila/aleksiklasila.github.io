'use strict';
const assert=require('node:assert/strict'),A=require('./report-analysis.js');
const row=(focal,opponent,a,b,extra={})=>({focal,opponent,scenario:'fixture',balanceMode:'equal-energy',engaged:true,contaminated:false,mode:'combat',level:1,research:0,sides:[{healthEnergyLossFraction:a},{healthEnergyLossFraction:b}],...extra});
const rows=[row('normal','tank',.8,.2),row('tank','normal',.4,.6),row('normal','normal',.5,.1),row('normal','tank',1,0,{level:5,research:5}),row('normal','tank',0,1,{balanceMode:'equal-numbers'})];
const defaults={energy:true,numbers:false,self:false,mixed:false,idle:false,hazards:false,bounded:true};
const filtered=rows.filter(r=>A.matches(r,defaults));assert.equal(filtered.length,3);
const m=A.dangerMatrix(filtered,['normal','tank'],{level:'1',research:'0'}),get=(y,x)=>m.cells.get(JSON.stringify([y,x]));
assert.equal(get('normal','tank').count,2);
assert(Math.abs(get('normal','tank').lossY-.7)<1e-10);
assert(Math.abs(get('normal','tank').lossX-.3)<1e-10);
assert(Math.abs(get('normal','tank').danger-40)<1e-10,'positive/red means more loss to Y');
assert(Math.abs(get('tank','normal').danger+40)<1e-10,'reverse cell uses actual reverse-side losses');
assert.equal(get('normal','normal'),undefined,'self-match diagonal stays blank by default');
assert.equal(m.grid[0][0],null,'no measurement is not a neutral matchup');
const controls=A.dangerMatrix(rows.filter(r=>A.matches(r,{...defaults,self:true})),['normal','tank']);
assert(Math.abs(controls.cells.get('["normal","normal"]').danger-100*2/3)<1e-10,'self controls keep relative side asymmetry');
assert.equal(rows.filter(r=>A.matches(r,{...defaults,energy:false,numbers:true})).length,1);
assert.equal(rows.filter(r=>A.matches(r,{...defaults,energy:false})).length,0);
const only=A.dangerMatrix(filtered,['normal','tank'],{level:'5',research:'5',victim:'normal',threat:'tank'});
assert.deepEqual(only.xs,['tank']);assert.deepEqual(only.ys,['normal']);assert.equal(only.grid[0][0].danger,100);
assert(!A.matches(row('a','b',1,0,{contaminated:true}),defaults));
assert(!A.matches(row('a','b',1,0,{countBounded:true}),{...defaults,bounded:false}));
assert(Math.abs(A.relativeDanger(.58,.04)-87.0967741935)<1e-8);
assert.equal(A.relativeDanger(.99,.45),37.5);
assert(A.relativeDanger(.58,.04)>A.relativeDanger(.99,.45),'14.5x loss is more dangerous than 2.2x despite the same percentage-point gap');
assert.equal(A.relativeDanger(0,0),0);assert.equal(A.relativeDanger(1,0),100);assert.equal(A.relativeDanger(0,1),-100);
assert.equal(A.relativeDanger(.4,.4),0);
assert(Math.abs(A.relativeDanger(.058,.004)-A.relativeDanger(.58,.04))<1e-10,'Relative danger is invariant to the overall damage scale');
console.log('PASS report defaults, independent filters, danger direction, mirrored observations, missing cells and self controls');
